def sumar_dos_numeros(num1: int, num2: int) -> int:
    """
    Suma dos números enteros y devuelve el resultado.

    Args:
        num1 (int): Primer número entero.
        num2 (int): Segundo número entero.

    Returns:
        int: La suma de `num1` y `num2`.

    Examples:
        >>> sumar_dos_numeros(3, 5)
        8
    """
    return num1 + num2


print(sumar_dos_numeros(2, 3))
